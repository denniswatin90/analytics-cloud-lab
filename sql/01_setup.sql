-- 01_setup.sql — warehouse, database, schemas, roles, cost guardrails
-- Run in a Snowsight worksheet as ACCOUNTADMIN (trial account).

-- 1. Roles (SECURITYADMIN owns role management)
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LAB_ENGINEER COMMENT = 'Builds and loads the lab';
CREATE ROLE IF NOT EXISTS LAB_ANALYST  COMMENT = 'Read-only on ANALYTICS';
GRANT ROLE LAB_ANALYST  TO ROLE LAB_ENGINEER;   -- engineer inherits analyst
GRANT ROLE LAB_ENGINEER TO ROLE SYSADMIN;       -- keep the role hierarchy tidy
SET my_user = CURRENT_USER();
GRANT ROLE LAB_ENGINEER TO USER IDENTIFIER($my_user);

-- 2. Compute: smallest warehouse, suspends after 60 s idle
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LAB_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
GRANT USAGE, OPERATE ON WAREHOUSE LAB_WH TO ROLE LAB_ENGINEER;
GRANT USAGE ON WAREHOUSE LAB_WH TO ROLE LAB_ANALYST;

-- 3. Storage
CREATE DATABASE IF NOT EXISTS MAC_LAB;
CREATE SCHEMA IF NOT EXISTS MAC_LAB.RAW;        -- landed data
CREATE SCHEMA IF NOT EXISTS MAC_LAB.ANALYTICS;  -- views/tables clients query
CREATE SCHEMA IF NOT EXISTS MAC_LAB.SHARED;     -- secure views exposed via shares
GRANT OWNERSHIP ON DATABASE MAC_LAB TO ROLE LAB_ENGINEER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE MAC_LAB TO ROLE LAB_ENGINEER COPY CURRENT GRANTS;

-- 4. Analyst read access (including future objects)
USE ROLE LAB_ENGINEER;
GRANT USAGE ON DATABASE MAC_LAB TO ROLE LAB_ANALYST;
GRANT USAGE ON SCHEMA MAC_LAB.ANALYTICS TO ROLE LAB_ANALYST;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA MAC_LAB.ANALYTICS TO ROLE LAB_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA MAC_LAB.ANALYTICS TO ROLE LAB_ANALYST;

-- 5. Cost guardrail: notify at 80%, suspend at 100% of 10 credits/month
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR IF NOT EXISTS LAB_MONITOR
  WITH CREDIT_QUOTA = 10
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE LAB_WH SET RESOURCE_MONITOR = LAB_MONITOR;

-- Check
SHOW WAREHOUSES LIKE 'LAB_WH';
SHOW GRANTS TO ROLE LAB_ENGINEER;
